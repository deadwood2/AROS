#!/usr/bin/env python3
"""Generate deterministic QEMU virtual-field configurations; never execute QEMU."""
import argparse
import json
from pathlib import Path

ALLOWED = {"name", "memory_mb", "cpus", "disk", "iso", "network", "display", "network_adapter"}
def build_field(spec):
    unknown = set(spec) - ALLOWED
    if unknown:
        raise ValueError("Unknown fields: " + ", ".join(sorted(unknown)))
    name = spec.get("name", "AROS Virtual Field")
    if not isinstance(name, str) or not (1 <= len(name) <= 80):
        raise ValueError("Invalid field name")
    memory = spec.get("memory_mb", 2048)
    cpus = spec.get("cpus", 2)
    if type(memory) is not int or not 256 <= memory <= 65536:
        raise ValueError("memory_mb must be an integer between 256 and 65536")
    if type(cpus) is not int or not 1 <= cpus <= 32:
        raise ValueError("cpus must be an integer between 1 and 32")
    args = ["qemu-system-x86_64", "-name", name, "-m", str(memory), "-smp", str(cpus)]
    display = spec.get("display", "gtk")
    if display not in ("gtk", "sdl", "none"):
        raise ValueError("Unsupported display")
    args += ["-display", display]
    for key, flag in (("disk", "-drive"), ("iso", "-cdrom")):
        value = spec.get(key)
        if value is not None:
            if not isinstance(value, str) or not value.strip() or "\x00" in value:
                raise ValueError("Invalid " + key)
            if key == "disk":
                args += [flag, "file=" + value.replace(",", ",,") + ",format=qcow2,if=ide"]
            else:
                args += [flag, value]
    network = spec.get("network", True)
    if type(network) is not bool:
        raise ValueError("network must be boolean")
    adapter = spec.get("network_adapter", "e1000")
    if adapter not in ("e1000", "pcnet"):
        raise ValueError("network_adapter must be e1000 or pcnet")
    args += ["-nic", "user,model=" + adapter if network else "none"]
    return {"schema": 1, "name": name, "qemu_argv": args, "execution": "manual-review-required"}

def main():
    parser = argparse.ArgumentParser(description="QEMU virtual field generator")
    parser.add_argument("spec", type=Path, help="JSON specification, optionally generated by AI")
    parser.add_argument("--output", type=Path)
    ns = parser.parse_args()
    field = build_field(json.loads(ns.spec.read_text(encoding="utf-8")))
    result = json.dumps(field, indent=2, ensure_ascii=False) + "\n"
    if ns.output:
        ns.output.write_text(result, encoding="utf-8")
    else:
        print(result, end="")

if __name__ == "__main__":
    main()
